OWNER_FILE = os.path.join(DATA_DIR, 'session_owner.json')
SESSION_OWNER:    int | None = None
LOGIN_PENDING_BY: int | None = None


def load_session_owner() -> int | None:
    global SESSION_OWNER
    try:
        with open(OWNER_FILE, 'r', encoding='utf-8') as fh:
            data = json.load(fh)
        raw = data.get('user_id')
        SESSION_OWNER = int(raw) if raw else None
    except (OSError, ValueError, TypeError):
        SESSION_OWNER = None
    if SESSION_OWNER:
        logger.info('Loaded session owner: %s', SESSION_OWNER)
    return SESSION_OWNER


def set_session_owner(user_id: int | None) -> None:
    global SESSION_OWNER
    SESSION_OWNER = int(user_id) if user_id else None
    try:
        with open(OWNER_FILE, 'w', encoding='utf-8') as fh:
            json.dump({'user_id': SESSION_OWNER}, fh)
    except OSError:
        logger.warning('Could not persist session owner: %s', OWNER_FILE)


def current_owner() -> int | None:
    global SESSION_OWNER
    if SESSION_OWNER is None:
        return None
    try:
        st = bridge.status()
        if not st.get('loggedIn'):
            set_session_owner(None)
            return None
    except BridgeError:
        return SESSION_OWNER
    return SESSION_OWNER


def owner_blocked(user_id: int) -> str | None:
    owner = current_owner()
    if owner is None:
        return (
            '❌ No WhatsApp session is linked.\n'
            'Use /login to scan a QR — the user who scans it becomes the only one who can use the bot.'
        )
    if user_id != owner:
        return (
            "❌ This bot is linked to another user's WhatsApp number. "
            'Ask them to /logout when done.'
        )
    return None


def qr_to_bytes(qr_string: str) -> io.BytesIO:
    img = qrcode.make(qr_string)
    buf = io.BytesIO()
    img.save(buf, format='PNG')
    buf.seek(0)
    return buf

