class BridgeError(Exception):
    pass


class Bridge:
    def __init__(self, host: str, port: int, token: str = ''):
        self.base  = f'http://{host}:{port}'
        self.token = token

    def _request(self, method: str, path: str, body=None, timeout: int = 60):
        url  = self.base + path
        data = None
        headers: dict[str, str] = {}
        if body is not None:
            data = json.dumps(body).encode('utf-8')
            headers['Content-Type'] = 'application/json'
        if self.token:
            headers['Authorization'] = f'Bearer {self.token}'
        req = urllib_request.Request(url, data=data, headers=headers, method=method)
        try:
            with urllib_request.urlopen(req, timeout=timeout) as resp:
                return json.loads(resp.read().decode('utf-8'))
        except urllib_error.HTTPError as e:
            try:
                payload = json.loads(e.read().decode('utf-8'))
                raise BridgeError(payload.get('error', f'HTTP {e.code}')) from e
            except json.JSONDecodeError:
                raise BridgeError(f'HTTP {e.code}') from e
        except urllib_error.URLError as e:
            raise BridgeError(f'Cannot reach bridge: {e.reason}') from e

    def health(self):           return self._request('GET',  '/health',               timeout=5)
    def status(self):           return self._request('GET',  '/status',               timeout=10)
    def login(self):            return self._request('POST', '/login',                timeout=10)
    def get_qr(self):           return self._request('GET',  '/qr',                   timeout=10)
    def logout(self):           return self._request('POST', '/logout',               timeout=30)
    def join_group(self, link): return self._request('POST', '/join-group', {'link': link}, timeout=60)
    def is_admin(self, gid):    return self._request('GET',  f'/admin/{quote(gid, safe="")}',   timeout=30)
    def get_members(self, gid): return self._request('GET',  f'/members/{quote(gid, safe="")}', timeout=30)
    def start_add(self, gid, contacts, batch_size, delay_seconds):
        return self._request('POST', '/add', {
            'groupId': gid, 'contacts': contacts,
            'batchSize': batch_size, 'delaySeconds': delay_seconds,
        }, timeout=15)
    def get_job(self, job_id):    return self._request('GET',  f'/jobs/{job_id}',        timeout=15)
    def cancel_job(self, job_id): return self._request('POST', f'/jobs/{job_id}/cancel', timeout=10)


