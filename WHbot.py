async def _health_handler(reader, writer):
    try:
        await reader.read(4096)
    except Exception:
        pass
    try:
        writer.write(b'HTTP/1.1 200 OK\r\nContent-Length: 2\r\nConnection: close\r\n\r\nOK')
        await writer.drain()
    except Exception:
        pass
    finally:
        writer.close()
        try:
            await writer.wait_closed()
        except Exception:
            pass


async def start_health_server() -> asyncio.Server | None:
    try:
        server = await asyncio.start_server(_health_handler, '0.0.0.0', PORT)
        logger.info('Health server on port %s', PORT)
        return server
    except OSError as e:
        logger.warning('Health server failed on port %s: %s', PORT, e)
        return None

