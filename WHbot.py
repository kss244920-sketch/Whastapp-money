async def on_document(update: Update, context: ContextTypes.DEFAULT_TYPE):
    user_id = update.effective_user.id
    if not allowed(user_id):
        return
    blocked = owner_blocked(user_id)
    if blocked:
        return await update.message.reply_text(blocked)

    flow = get_flow(user_id)
    doc  = update.message.document

    if not (doc.file_name or '').lower().endswith('.vcf'):
        return await update.message.reply_text('Please send a `.vcf` file.')

    if flow.state != 'waiting_vcf':
        return await update.message.reply_text(
            'You are not in the "waiting for VCF" step.\n'
            'Use /join <group_link> first and wait for admin confirmation.'
        )

    tmp_path = os.path.join(tempfile.gettempdir(), f'contacts_{user_id}_{int(time.time())}.vcf')
    try:
        file = await doc.get_file()
        await file.download_to_drive(tmp_path)
        contacts = parse_vcf(tmp_path, DEFAULT_COUNTRY_CODE)
    except Exception as e:
        logger.exception('VCF parse failed')
        return await update.message.reply_text(f'❌ Could not parse VCF: {e}')
    finally:
        try:
            os.remove(tmp_path)
        except OSError:
            pass

    if not contacts:
        return await update.message.reply_text(
            '⚠️ No usable numbers found in the VCF.\n'
            'Check numbers include a country code, or set DEFAULT_COUNTRY_CODE.'
        )

    flow.contacts = [f'{num}@c.us' for num in contacts]
    keyboard = InlineKeyboardMarkup([[
        InlineKeyboardButton('✅ Start adding', callback_data='start_add'),
        InlineKeyboardButton('❌ Cancel',       callback_data='cancel_add'),
    ]])
    await update.message.reply_text(
        f'📇 Found *{len(contacts)} unique numbers* in the VCF.\n'
        f'Adding to *"{flow.group_name}"* in batches of {BATCH_SIZE} '
        f'with {BATCH_DELAY_SECONDS}s delay.\n\nStart?',
        reply_markup=keyboard,
        parse_mode='Markdown',
    )


async def on_callback(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()
    user_id = query.from_user.id
    if not allowed(user_id):
        return
    blocked = owner_blocked(user_id)
    if blocked:
        return await query.edit_message_text(blocked)

    flow = get_flow(user_id)
    if query.data == 'cancel_add':
        flow.contacts = []
        flow.state    = 'idle'
        return await query.edit_message_text('Cancelled.')

    if query.data == 'start_add':
        if not flow.contacts or not flow.group_id:
            flow.state = 'idle'
            return await query.edit_message_text('❌ Missing data. Start over with /join.')
        await query.edit_message_text('🚀 Adding contacts… I will send progress updates.')
        APP.create_task(run_add_flow(query.message.chat_id, user_id))


async def run_add_flow(chat_id: int, user_id: int):
    flow       = get_flow(user_id)
    flow.state = 'adding'
    try:
        res         = bridge.start_add(flow.group_id, flow.contacts, BATCH_SIZE, BATCH_DELAY_SECONDS)
        flow.job_id = res['jobId']
        last_rep    = 0

        while True:
            job    = bridge.get_job(flow.job_id)
            status = job.get('status')
            if status in ('done', 'error', 'cancelled'):
                break
            done = job.get('doneBatches', 0)
            if done > last_rep:
                last_rep = done
                await APP.bot.send_message(
                    chat_id,
                    f'📦 Batch {done}/{job.get("totalBatches","?")} — '
                    f'added {job.get("added",0)}, failed {job.get("failed",0)}.',
                )
            await asyncio.sleep(ADD_POLL_SECONDS)

        if status == 'done':
            result  = job.get('result', {})
            added   = result.get('added',  [])
            failed  = result.get('failed', [])
            members = bridge.get_members(flow.group_id)
            lines   = [
                '✅ *Adding complete!*', '',
                f'• Added:           *{len(added)}*',
                f'• Already in group: *{result.get("alreadyCount", 0)}*',
                f'• Failed:          *{len(failed)}*',
                f'• Final group size: *{members.get("count","?")}*',
            ]
            if failed:
                sample = ', '.join(f.get('id','?').split('@')[0] for f in failed[:10])
                lines.append(f'\n⚠️ Failed ({len(failed)}): {sample}')
                if len(failed) > 10:
                    lines.append('…')
            await APP.bot.send_message(chat_id, '\n'.join(lines), parse_mode='Markdown')
        elif status == 'cancelled':
            await APP.bot.send_message(chat_id, '❌ Adding was cancelled.')
        else:
            await APP.bot.send_message(chat_id, f'❌ Adding failed: {job.get("error","unknown")}')
    except BridgeError as e:
        await APP.bot.send_message(chat_id, f'❌ Error: {e}')
    except Exception as e:
        logger.exception('run_add_flow failed')
        await APP.bot.send_message(chat_id, f'❌ Unexpected error: {e}')
    finally:
        flow.state    = 'idle'
        flow.contacts = []
        flow.job_id   = None


