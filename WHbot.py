async def ensure_bridge_running() -> subprocess.Popen | None:
    try:
        bridge.health()
        logger.info('Reusing already-running bridge.')
        return None
    except BridgeError:
        pass

    script   = _write_bridge_script()
    bot_dir  = os.path.dirname(os.path.abspath(__file__))
    # node_modules must be next to WHbot.py (after npm install)
    cwd = bot_dir
    if not os.path.isdir(os.path.join(bot_dir, 'node_modules')):
        logger.warning(
            'node_modules not found in %s. Run: npm install', bot_dir
        )

    env = dict(os.environ)
    env.setdefault('WWEBJS_AUTH_PATH', os.path.join(DATA_DIR, '.wwebjs_auth'))

    proc = subprocess.Popen(['node', script], cwd=cwd, env=env)

    for _ in range(BRIDGE_START_TIMEOUT):
        try:
            bridge.health()
            logger.info('Bridge started (pid %s).', proc.pid)
            return proc
        except BridgeError:
            await asyncio.sleep(1)

    try:
        proc.terminate()
    except Exception:
        pass
    raise RuntimeError(
        'Bridge failed to start within 60 s.\n'
        'Make sure Node.js >= 18 is installed and you ran: npm install'
    )

