_NON_DIGITS = re.compile(r'\D')


def normalize_number(raw: str, default_cc: str = DEFAULT_COUNTRY_CODE) -> str | None:
    raw = str(raw).strip()
    if not raw:
        return None
    explicit_cc = raw.startswith('+')
    digits = _NON_DIGITS.sub('', raw)
    if not digits:
        return None
    if digits.startswith('00'):
        explicit_cc = True
        digits = digits[2:]
    if digits.startswith('0'):
        digits = digits[1:]
    if not explicit_cc and 10 <= len(digits) <= 11:
        digits = default_cc + digits
    if len(digits) < 10 or len(digits) > 15:
        return None
    return digits


def parse_vcf(file_path: str, default_cc: str = DEFAULT_COUNTRY_CODE) -> list[str]:
    try:
        import vobject
    except ImportError as exc:
        raise RuntimeError('Run: pip install -r requirements.txt') from exc

    with open(file_path, 'r', encoding='utf-8', errors='ignore') as fh:
        data = fh.read()

    numbers: list[str] = []
    try:
        for vcard in vobject.readComponents(data):
            tels = getattr(vcard, 'tel_list', [])
            if not tels and getattr(vcard, 'tel', None):
                tels = [vcard.tel]
            for tel in tels:
                num = normalize_number(tel.value, default_cc)
                if num:
                    numbers.append(num)
    except Exception as exc:
        raise ValueError(f'Malformed VCF: {exc}') from exc

    seen: set[str] = set()
    unique: list[str] = []
    for num in numbers:
        if num not in seen:
            seen.add(num)
            unique.append(num)
    return unique

